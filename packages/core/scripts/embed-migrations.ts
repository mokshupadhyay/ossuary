/*
 * Writes src/poltergeist/embeddedMigrations.generated.ts from src/migrations,
 * so a browser can migrate PGlite without reading files (poltergeist-engine
 * Requirement 14.4, design D8). The output is exactly what drizzle's
 * readMigrationFiles builds, hash included. Run after adding a migration:
 *
 *   pnpm --filter core embed-migrations
 *
 * tests/unit/embeddedMigrations.test.ts fails if the file is out of date.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readMigrationFiles } from 'drizzle-orm/migrator';

const migrationsFolder = fileURLToPath(new URL('../src/migrations', import.meta.url));
const out = fileURLToPath(new URL('../src/poltergeist/embeddedMigrations.generated.ts', import.meta.url));

const migrations = readMigrationFiles({ migrationsFolder });
const body = migrations
  .map(
    (m) =>
      `  {\n    folderMillis: ${m.folderMillis},\n    bps: ${m.bps},\n    hash: ${JSON.stringify(m.hash)},\n    sql: ${JSON.stringify(m.sql, null, 2).replace(/\n/g, '\n    ')},\n  },`,
  )
  .join('\n');

writeFileSync(
  out,
  `// GENERATED by scripts/embed-migrations.ts from src/migrations. Do not edit.
// Regenerate with: pnpm --filter core embed-migrations
import type { MigrationMeta } from 'drizzle-orm/migrator';

export const EMBEDDED_MIGRATIONS: readonly MigrationMeta[] = [
${body}
];
`,
);
console.log(`wrote ${migrations.length} migrations to ${out}`);
